"""Regenerate results/tables/ from results/runs/ (§12.6).

Two rules this enforces, and they are the whole point of the file:

1. **A run made against a dirty git tree is refused.** An untracked local edit must not be
   able to change a published number silently.
2. **Every generated table carries the run_id it came from**, as a LaTeX comment and in the
   caption, so any figure in the paper can be traced back to the code and environment that
   produced it.

Nothing here computes a statistic. It formats what a runner already measured.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from fcesreg.paths import results_path
from fcesreg.runs import RESULTS_ROOT, load_run

TABLES_ROOT = results_path("tables")


class DirtyRun(RuntimeError):
    """Refusing to build a table from a run made against an uncommitted tree."""


def latest_run(script: str, root: Path = RESULTS_ROOT) -> str:
    """Most recent run id for a script. Run ids sort chronologically by construction."""
    candidates = sorted(d.name for d in root.iterdir() if d.name.startswith(f"{script}-"))
    if not candidates:
        raise FileNotFoundError(f"no runs found for {script} under {root}")
    return candidates[-1]


def _require_clean(run: dict) -> None:
    if run["env"].get("git_dirty"):
        raise DirtyRun(
            f"run {run['run_id']} was made against a dirty git tree "
            f"(sha {run['env'].get('git_short_sha')}). Commit the tree and re-run it. "
            "A number that cannot be traced to a commit does not go in the paper."
        )


def _esc(s: str) -> str:
    return str(s).replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def _wrap(body: str, caption: str, label: str, run_id: str, spec: str, compact: bool = False) -> str:
    """``compact=True`` scopes ``\\footnotesize`` and a tighter ``\\tabcolsep`` to just this
    table's ``tabular`` (braced, not ``\\resizebox`` -- scaling a table changes its font size
    relative to the body rather than fixing the actual overflow). Use it where a table's own
    column count/width genuinely needs it, not as a blanket default."""
    pre = "{\\footnotesize\\setlength{\\tabcolsep}{4pt}\n" if compact else ""
    post = "}\n" if compact else ""
    return (
        f"% generated by make_tables.py from run {run_id}\n"
        "% do not edit — regenerate with `make tables`\n"
        "\\begin{table}[t]\n\\centering\n"
        f"\\caption{{{caption}}}\n"
        f"\\label{{{label}}}\n"
        f"{pre}"
        f"\\begin{{tabular}}{{{spec}}}\n\\hline\n"
        f"{body}"
        "\\hline\n\\end{tabular}\n"
        f"{post}"
        "\\end{table}\n"
    )


def table_corpus(run: dict) -> str:
    """Both corpora's size and split, merged into one exhibit (supervisor ruling: five
    tables not eleven). Corpus A's unit is a labelled pair; Corpus B's is a record, split
    by division set rather than train/valid/test since the adopted set is the point being
    shown. The two blocks share columns loosely (n, a held-out count, a rate) rather than
    exactly, documented in the caption rather than forced into an artificial match.
    """
    a = run["metrics"]["corpus_a_abtbuy"]
    b = run["metrics"]["corpus_b_contractsfinder"]
    adopted = b["adopted_division_set"]

    rows = ["Corpus & Unit & n & Held out & Rate \\\\\n\\hline\n"]
    for split in ("train", "valid", "test"):
        s = a["splits"][split]
        rows.append(
            f"A: {split} & pairs & {s['n_pairs']:,} & --- & "
            f"{100 * s['positive_rate']:.1f}\\% positive \\\\\n"
        )
    rows.append(
        f"A: total & pairs & {a['n_pairs']:,} & --- & "
        f"{100 * a['positive_rate_overall']:.1f}\\% positive \\\\\n"
    )
    rows.append("\\hline\n")
    for name, d in b["division_sets"].items():
        lvl = d["levels"]["class"]
        mark = " (adopted)" if name == adopted else ""
        rows.append(
            f"B: {len(d['divisions'])} div.{mark} & records & {d['n_records']:,} & "
            f"{d['n_test']:,} test & {100 * lvl['coverage_of_dev']:.1f}\\% cov. \\\\\n"
        )
    caption = (
        f"Corpus A (Abt-Buy): {a['n_records']:,} records "
        f"({a['n_records_table_a']:,} + {a['n_records_table_b']:,}), supplied splits. "
        f"Corpus B (Contracts Finder): records by retained division set, temporal split at "
        f"{b['split']['cutoff']}. Rate: positive share of pairs (A); class-level coverage "
        f"of the development partition at $\\geq$50 training examples (B)."
    )
    return _wrap("".join(rows), caption, "tab:corpus", run["run_id"], "llrrr")


def table_discard(run: dict) -> str:
    d = run["metrics"]["corpus_b_contractsfinder"]["discard"]
    rows = ["Year & In & Out of scope & Short & Desc = title & Boilerplate & Out \\\\\n\\hline\n"]
    for year in sorted(d["per_year"]):
        r = d["per_year"][year]
        rows.append(
            f"{year} & {r['total_in']:,} & {r['dropped_out_of_scope']:,} & "
            f"{r['dropped_short']:,} & {r['dropped_desc_equals_title']:,} & "
            f"{r['dropped_boilerplate']:,} & {r['total_out']:,} \\\\\n"
        )
    c = d["combined"]
    rows.append("\\hline\n")
    rows.append(
        f"total & {c['total_in']:,} & {c['dropped_out_of_scope']:,} & "
        f"{c['dropped_short']:,} & {c['dropped_desc_equals_title']:,} & "
        f"{c['dropped_boilerplate']:,} & {c['total_out']:,} \\\\\n"
    )
    caption = (
        "Records discarded by each rule, applied in order so that every input row is "
        "attributed to the first rule it fails."
    )
    return _wrap("".join(rows), caption, "tab:discard", run["run_id"], "lrrrrrr")


